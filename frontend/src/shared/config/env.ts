// 프론트 환경변수의 단일 진입점.
//
// 왜 한 곳으로 모으나 — 예전에는 client.ts와 answers.ts가 각자 import.meta.env를 읽었다.
// 그러면 "값이 없을 때 어떻게 할지"를 바꾸려면 여러 파일을 고쳐야 하고, 한 곳을 빠뜨리면 동작이 갈린다.
//
// 규격·주입 경로·보안 성격: docs/architecture/toolchain.md §6
//   - VITE_ 접두 변수만 클라이언트에 노출되고, 값은 빌드타임에 정적 치환된다.
//   - 따라서 번들에 그대로 박힌다 — 비밀을 넣지 않는다. 이 값은 secret이 아니라 환경별 설정값이다.

/**
 * API 오리진. **끝에 슬래시가 없어야 한다** — 호출부가 `${API_BASE}${path}` 로 이어붙이고
 * path가 전부 "/"로 시작하기 때문이다. 슬래시를 붙이면 `//api/v1/...` 이 된다.
 *
 * 값이 없으면 빈 문자열이 되어 **같은 오리진(상대 경로)** 으로 요청이 나간다.
 * 이는 의도된 폴백이 아니라 **현재 백엔드 호스트가 정해지지 않았기 때문의 잠정 상태**다.
 * 미설정과 "같은 오리진 의도"가 구분되지 않는 문제는 `isApiBaseConfigured` 로 드러낸다.
 */
export const API_BASE: string = import.meta.env.VITE_API_BASE ?? "";

/**
 * `VITE_API_BASE` 가 실제로 주입됐는지.
 *
 * 빌드타임 정적 치환이라 런타임에 바뀌지 않는다. 값 부재는 다음 경우에 발생한다:
 *   - 로컬에서 `.env` 에 값을 안 넣었을 때 (백엔드 호스트 미확정 — 현재 상태)
 *   - **포크에서 온 PR** — GitHub은 포크 PR 러너에 secret을 전달하지 않는다
 *
 * 지금은 동작을 바꾸지 않는다(상대 경로 유지). 백엔드 호스트가 확정되면 이 플래그를 근거로
 * 빌드 실패나 진입 시 경고로 승격한다 — 그때 고칠 파일은 이 한 곳이다.
 */
export const isApiBaseConfigured: boolean = API_BASE !== "";
