// AI 생성물 고지 — 법적 리스크 대응(2026-08-30, 사용자 요청).
//
// ## 왜 필요한가
//
// 이 서비스가 다루는 것은 **계약**이다. 00_BASELINE.md §1 의 문제 정의부터가 "진짜 함정은
// '얼마'가 아니라 '계약 조건'"이고, 근거로 쓰는 자료도 공정위 표준약관·소비자원 분쟁해결기준
// 원문이다. 사용자가 AI 답변을 계약 판단의 근거로 받아들이는 것이 **설계상 의도된 사용법**이라는
// 뜻이다. 그런데 그 답변은 LLM 생성물이라 언제든 틀릴 수 있다 — 이 간극을 화면에서 고지하지
// 않으면, 잘못된 답변이 실제 금전 손해로 이어졌을 때 서비스가 방어할 근거가 없다.
//
// ## 왜 답변 본문에 붙이지 않고 UI 층에 두는가
//
// 세 가지 이유로 프롬프트에 "면책 문구를 붙여라"를 넣지 않았다.
//   1. **LLM 이 빠뜨릴 수 있다.** 이 저장소는 프롬프트 지시로 출력을 통제하려다 같은 클래스
//      버그를 4번 재발시킨 이력이 있다(개인화 category_code — app/personalization/graph.py).
//      고지는 누락되면 안 되는 것이므로 확률적 장치에 맡기지 않는다.
//   2. **토큰을 매 답변마다 태운다.** 고정 문자열을 LLM 이 매번 다시 생성할 이유가 없다.
//   3. **DB 에 중복 저장된다.** chat_messages.content 마다 같은 문구가 박히면 나중에 문구를
//      고쳐도 과거 답변은 옛 문구로 남는다.
// UI 층에 두면 셋 다 없고, 문구 수정이 한 곳에서 끝난다.
//
// ## 왜 StatusCallout 이 아닌가
//
// `StatusCallout` 은 조건이 참일 때만 나타나는 **라이브 리전**(`<output>`, 암묵 role=status)이다.
// 스크린리더가 등장 순간 낭독하는 것이 그 컴포넌트의 존재 이유인데, 고지는 화면에 상시 있는
// 정적 텍스트라 낭독을 가로챌 일이 아니다. 리전으로 만들면 화면 전환마다 면책 문구가 읽혀
// 정작 중요한 상태 변화 낭독을 방해한다.
//
// ## 문구를 상수로 뽑아둔 이유
//
// 법무 검토가 들어오면 문구가 바뀐다. 그때 고쳐야 할 곳이 여기 하나여야 한다 —
// 호출부 3곳(AI상담·체크리스트·타임라인)이 각자 문자열을 들고 있으면 반드시 하나가 남는다.
import type { ReactNode } from "react";

/** AI상담(대화형 답변)용 — 계약·법률 판단으로 오해되는 것을 막는 것이 목적이다. */
export const AI_CHAT_DISCLAIMER =
  "AI가 자료를 검색해 생성한 참고 정보입니다. 법률·계약 자문이 아니며 사실과 다를 수 있으니, " +
  "실제 계약 전에는 계약서 원문과 업체·전문가 확인을 거쳐주세요.";

/** 개인화 생성물(체크리스트·타임라인)용 — 사용자가 "우리 상황에 맞춰 확정된 계획"으로 읽지 않게 한다. */
export const AI_PLAN_DISCLAIMER =
  "입력하신 정보를 바탕으로 AI가 만든 참고용 목록입니다. 빠지거나 맞지 않는 항목이 있을 수 있으니 " +
  "실제 일정과 계약 조건은 업체와 직접 확인해주세요.";

// `text-xs`·`text-ink-soft` — 본문보다 한 단계 낮은 위계다. 고지는 읽혀야 하지만 화면의 주인공이
// 아니다(The One Accent Rule — 강조색을 쓰지 않는다). 경고색(risk)도 쓰지 않는다: 이건 오류나
// 위험 상태가 아니라 상시 안내라, 매번 빨간 블록이 뜨면 실제 경고의 신호가치가 닳는다.
//
// `border-t` 로 본문과 선을 그어 "이건 답변의 일부가 아니다"를 시각적으로 분리한다.
const WRAP = "mt-3 border-t border-line pt-3 text-xs leading-relaxed text-ink-soft";

export interface AiDisclaimerProps {
  /** AI_CHAT_DISCLAIMER · AI_PLAN_DISCLAIMER 중 하나를 넘긴다. */
  children: ReactNode;
}

export function AiDisclaimer({ children }: AiDisclaimerProps) {
  // <p> 가 아니라 <aside> — 본문의 흐름이 아니라 부수 정보라는 것을 마크업으로도 남긴다.
  // 스크린리더 사용자가 랜드마크 목록에서 건너뛸 수 있다(상시 문구라 매번 들을 이유가 없다).
  return (
    <aside aria-label="AI 생성 정보 안내" className={WRAP}>
      {children}
    </aside>
  );
}
