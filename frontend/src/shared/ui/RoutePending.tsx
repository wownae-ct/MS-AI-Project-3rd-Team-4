// 라우트 전환 대기 표시 — `createRouter({ defaultPendingComponent })` 에 등록해 쓴다. D14.
//
// ## 이것이 닫는 구멍
//
// 그동안 탭을 눌러도 화면이 **그대로 멈춰 있다가** 갑자기 바뀌었다. lazy 청크가 도착하고
// 가드(`_authed` 세션 판정)가 끝날 때까지 아무 표시가 없었기 때문이다. `defaultPreload: 'intent'`
// 가 호버·터치로 그 구간을 줄여 주지만, 딥링크나 곧바로 탭하는 경우는 그대로 남는다.
//
// ## 지연·최소 표시는 라우터가 이미 갖고 있다 — 여기서 다시 만들지 않는다
//
// 등록만 하면 TanStack 의 펜딩 기계가 통째로 켜진다(설치본 실측):
//   · `defaultPendingMs: 1000`      1초 안에 끝나는 전환에는 **아무것도 뜨지 않는다**
//   · `defaultPendingMinMs: 500`    한 번 뜨면 500ms 는 유지한다 (떴다 바로 사라지는 깜빡임 방지)
//   · 펜딩 컴포넌트가 **없으면** 펜딩 세션 자체를 만들지 않는다 — 그래서 지금까지 이 기계가
//     통째로 꺼져 있었다. 이 파일을 등록하는 것이 그 스위치다.
//
// ⚠️ 500ms 최소 표시는 공짜가 아니다 — 데이터가 준비돼도 그 시간을 채운 뒤 새 화면을 보여주므로
// **1000~1500ms 구간의 전환은 예전보다 느려진다.** 깜빡임 방지와 맞바꾼 값이고, 거슬리면
// `defaultPendingMinMs` 를 낮출 수 있다(그만큼 깜빡임 위험이 오른다).
//
// ## 레이아웃을 가정하지 않는다
//
// 이 컴포넌트가 그려지는 위치는 두 가지다.
//   · 탭 이동      — 셸(AppShell)은 그대로 있고 `<Outlet/>` 안, 즉 **콘텐츠 열**에 그려진다
//   · 딥링크 콜드  — `_authed`/`_shell` 가드가 아직 안 끝나 셸 **밖**(전체 화면)에 그려진다
// 그래서 셸 구조를 전제하지 않고 자기 높이만 확보한 뒤 가운데 정렬만 한다.
import { Loading } from "./Loading";

const WRAP = "flex min-h-64 items-center justify-center";

export function RoutePending() {
  // `delayMs={0}` — 라우터가 이미 1초를 기다린 뒤에 이 컴포넌트를 그린다. 여기서 또 지연을 걸면
  // 그 200ms 동안 콘텐츠 자리가 통째로 비어 보인다(직전 화면은 이미 치워진 뒤다).
  return (
    <div className={WRAP}>
      <Loading delayMs={0} />
    </div>
  );
}
